-- 과제 요구 트리거
--
-- 1) TRG_<테이블>_MOD_DTTM (MOD_DTTM 이 있는 17개 테이블)
--    UPDATE 후 MOD_DTTM 을 직접 바꾸지 않았으면 현재 시각을 기록한다. SQLite 에는 ON UPDATE 가 없다.
--    WHEN 조건 때문에 MOD_DTTM 이 이미 현재 시각이면 다시 UPDATE 하지 않는다.
--    그래서 recursive_triggers 를 켜도 무한 루프가 생기지 않는다.
--    주의: MOD_DTTM 을 원래와 같은 값으로 지정한 UPDATE 는 "직접 바꾸지 않음"으로 보아 현재 시각으로 덮어쓴다.
--
-- 2) TRG_ORD_CANCEL
--    주문 상태가 CANCEL 로 바뀌면 같은 트랜잭션에서 결제 취소, POINT 결제 환불, 라이더 대기 복귀를 한다.
--    FOR EACH ROW 이므로 여러 주문을 UPDATE 한 번으로 취소해도(10분 자동 취소) 주문마다 실행된다.
--    API 는 이 연쇄 변경을 다시 하지 않는다 (중복 환불 방지. UK_PNT_TXN_ORD_TYPE 도 막는다).
--
-- 라이더 BUSY 전환(D-05), 배달 완료 시 IDLE(D-08), 입점 승인 상태 동기화는 API 가 처리한다.

CREATE TRIGGER TRG_MBR_MOD_DTTM
AFTER UPDATE ON TB_MBR
FOR EACH ROW
WHEN NEW.MOD_DTTM IS OLD.MOD_DTTM AND NEW.MOD_DTTM IS NOT datetime('now', 'localtime')
BEGIN
  UPDATE TB_MBR SET MOD_DTTM = datetime('now', 'localtime') WHERE MBR_ID = NEW.MBR_ID;
END;

